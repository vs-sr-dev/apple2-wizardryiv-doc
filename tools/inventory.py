#!/usr/bin/env python3
"""Write notes/file-inventory.md: every directory record with LBA, size,
timestamp, SHA-1 and the first eight bytes."""
import json, os, hashlib, sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
t = json.load(open('_work/tree.json'))
base = '_work/files'
rows = []
for r in sorted(t['records'], key=lambda r: r['lba']):
    n = r['path'].split(';')[0]
    if r['dir']:
        rows.append((r['lba'], r['size'], r['date'][:19], n + '/', '', 'directory'))
        continue
    p = base + n
    h = hashlib.sha1(); head = b''
    with open(p, 'rb') as fh:
        while True:
            b = fh.read(1 << 20)
            if not b: break
            if not head: head = b[:8]
            h.update(b)
    rows.append((r['lba'], r['size'], r['date'][:19], n, h.hexdigest(), head.hex(' ')))
print('# File inventory\n')
print('Generated by `tools/inventory.py` from the directory records.\n')
print('| LBA | size | timestamp | file | SHA-1 | first 8 bytes |')
print('|---:|---:|---|---|---|---|')
for lba, size, date, name, sha, head in rows:
    print('| %d | %d | %s | `%s` | `%s` | `%s` |' % (lba, size, date, name, sha, head))
