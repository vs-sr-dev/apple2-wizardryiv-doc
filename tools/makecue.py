#!/usr/bin/env python3
"""makecue.py -- write a .cue from the TOC that was read off the disc.

Every previous disc in this set arrived as an image plus a .cue somebody else
had written, so the cue was a *source* and its CATALOG, track types and pregaps
were inherited claims.  Here the cue is an *output*: every field below is
derived from a device read performed by tools/rawcd.py, and the file says so in
its own REM lines so that it can never be mistaken for a third-party cue later.

Two fields are worth the note they get in the output:

  CATALOG   read from the subchannel Q MODE-2 field with MCVAL set, not copied
            from anywhere.  On this disc it is thirteen ASCII zeros.
  PREGAP    measured, not assumed: the 150 sectors before track 2's start
            address carry no sync pattern and are digital silence, and the
            data sectors stop exactly where they begin.

Usage: makecue.py <toc.json-or-none> <image-basename> > disc.cue
"""
import sys, json


def msf(lba):
    lba += 150
    return "%02d:%02d:%02d" % (lba // (60 * 75), (lba // 75) % 60, lba % 75)


# measured by tools/rawcd.py E toc / q, and by tools/rawsectors.py
TRACKS = [
    (1, 'MODE1/2048', 0),
    (2, 'AUDIO', 1068), (3, 'AUDIO', 12226), (4, 'AUDIO', 25575),
    (5, 'AUDIO', 46441), (6, 'AUDIO', 58891), (7, 'AUDIO', 65187),
    (8, 'AUDIO', 75646), (9, 'AUDIO', 92385), (10, 'AUDIO', 92994),
]
LEADOUT = 93513
CATALOG = "0000000000000"
DATA_SECTORS = 918          # sectors carrying a MODE1 sync pattern
PREGAP2 = 150               # silent sectors between them and track 2


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "alfredchicken"
    o = sys.stdout
    print("REM This cue was generated by tools/makecue.py from a TOC read off", file=o)
    print("REM the physical disc with IOCTL_CDROM_READ_TOC_EX.  It is NOT the", file=o)
    print("REM cue of a third-party dumper; no field here is inherited.", file=o)
    print("REM", file=o)
    print("REM CATALOG below was read from subchannel Q (MCVAL=1); thirteen", file=o)
    print("REM ASCII zeros is what the disc carries, not a missing field.", file=o)
    print("REM ISRC: absent on all ten tracks (TCVAL=0 on every one).", file=o)
    print("REM Track 1 is MODE1 verified by descrambling raw sectors and", file=o)
    print("REM reading the header byte, not assumed from the cue convention.", file=o)
    print("REM Data sectors: %d (LBA 0..%d).  The %d sectors from LBA %d to"
          % (DATA_SECTORS, DATA_SECTORS - 1, PREGAP2, DATA_SECTORS), file=o)
    print("REM %d carry no sync pattern and are silence: that is track 2's"
          % (DATA_SECTORS + PREGAP2 - 1), file=o)
    print("REM pregap, measured rather than assumed.", file=o)
    print("REM Lead-out LBA %d = MSF %s." % (LEADOUT, msf(LEADOUT)), file=o)
    print("REM", file=o)
    print("CATALOG %s" % CATALOG, file=o)
    print('FILE "%s.iso" BINARY' % base, file=o)
    print("  TRACK 01 MODE1/2048", file=o)
    print("    INDEX 01 00:00:00", file=o)
    print('FILE "%s.bin" BINARY' % base, file=o)
    for num, kind, lba in TRACKS[1:]:
        rel = lba - TRACKS[1][2]
        print("  TRACK %02d AUDIO" % num, file=o)
        if num == 2:
            print("    PREGAP %s" % msf(PREGAP2 - 150), file=o)
        print("    INDEX 01 %s" % msf(rel - 150), file=o)


if __name__ == '__main__':
    main()
